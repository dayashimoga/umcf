  String translate(String key) {
    final lang = locale.languageCode;
    return _localizedValues[lang]?[key] ?? _localizedValues['en']?[key] ?? key;
  }

  // Accessibility & WCAG 2.1 helpers
  static double calculateRelativeLuminance(Color color) {
    double transform(double c) {
      return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055).toDouble();
    }
    final r = transform(color.red / 255.0);
    final g = transform(color.green / 255.0);
    final b = transform(color.blue / 255.0);
    return 0.2126 * r + 0.7152 * g + 0.0722 * b;
  }

  static double calculateContrastRatio(Color foreground, Color background) {
    final l1 = calculateRelativeLuminance(foreground);
    final l2 = calculateRelativeLuminance(background);
    final lighter = l1 > l2 ? l1 : l2;
    final darker = l1 > l2 ? l2 : l1;
    return (lighter + 0.05) / (darker + 0.05);
  }

  static bool isWcagAaNormalText(Color foreground, Color background) {
    return calculateContrastRatio(foreground, background) >= 4.5;
  }

  static bool isWcagAaLargeText(Color foreground, Color background) {
    return calculateContrastRatio(foreground, background) >= 3.0;
  }
