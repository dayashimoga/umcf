//! Multi-dimensional resource metering collector and physical plausibility sanity guards.

use crate::error::LedgerError;
use serde::{Deserialize, Serialize};

/// Multi-dimensional vector of metered physical and compute resources.
/// All fields are strictly integer units (`u64`)—never floating point.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
pub struct MeteredResourceVector {
    /// Active CPU thread execution duration in microseconds.
    pub cpu_thread_time_us: u64,

    /// Fuel units consumed during WebAssembly runtime execution.
    pub wasm_fuel_consumed: u64,

    /// Hardware GPU compute shader execution duration in microseconds.
    pub gpu_compute_time_us: u64,

    /// Hardware NPU neural tensor execution duration in microseconds.
    pub npu_compute_time_us: u64,

    /// Peak GPU VRAM allocated multiplied by duration in seconds (byte-seconds).
    pub vram_peak_byte_seconds: u64,

    /// Number of prompt tokens evaluated by GGUF inference engine.
    pub ai_prompt_tokens: u64,

    /// Number of output tokens generated by GGUF inference engine.
    pub ai_generated_tokens: u64,

    /// Intermediate activation tensor shards transferred across network nodes.
    pub ai_layer_activations_transferred: u64,

    /// Number of video frames encoded or transcoded.
    pub media_frames_encoded: u64,

    /// Number of 3D raytraced or rendered pixels completed.
    pub render_pixels_completed: u64,

    /// Total outbound network payload bytes transferred.
    pub network_egress_bytes: u64,

    /// Total inbound network payload bytes received.
    pub network_ingress_bytes: u64,

    /// Total storage footprint multiplied by residency duration (byte-seconds).
    pub storage_byte_seconds: u64,
}

impl MeteredResourceVector {
    /// Zero-valued resource vector.
    #[must_use]
    pub const fn zero() -> Self {
        Self {
            cpu_thread_time_us: 0,
            wasm_fuel_consumed: 0,
            gpu_compute_time_us: 0,
            npu_compute_time_us: 0,
            vram_peak_byte_seconds: 0,
            ai_prompt_tokens: 0,
            ai_generated_tokens: 0,
            ai_layer_activations_transferred: 0,
            media_frames_encoded: 0,
            render_pixels_completed: 0,
            network_egress_bytes: 0,
            network_ingress_bytes: 0,
            storage_byte_seconds: 0,
        }
    }

    /// Canonical, deterministic little-endian binary encoding (104 bytes).
    #[must_use]
    pub fn to_canonical_bytes(&self) -> [u8; 104] {
        let mut buf = [0u8; 104];
        buf[0..8].copy_from_slice(&self.cpu_thread_time_us.to_le_bytes());
        buf[8..16].copy_from_slice(&self.wasm_fuel_consumed.to_le_bytes());
        buf[16..24].copy_from_slice(&self.gpu_compute_time_us.to_le_bytes());
        buf[24..32].copy_from_slice(&self.npu_compute_time_us.to_le_bytes());
        buf[32..40].copy_from_slice(&self.vram_peak_byte_seconds.to_le_bytes());
        buf[40..48].copy_from_slice(&self.ai_prompt_tokens.to_le_bytes());
        buf[48..56].copy_from_slice(&self.ai_generated_tokens.to_le_bytes());
        buf[56..64].copy_from_slice(&self.ai_layer_activations_transferred.to_le_bytes());
        buf[64..72].copy_from_slice(&self.media_frames_encoded.to_le_bytes());
        buf[72..80].copy_from_slice(&self.render_pixels_completed.to_le_bytes());
        buf[80..88].copy_from_slice(&self.network_egress_bytes.to_le_bytes());
        buf[88..96].copy_from_slice(&self.network_ingress_bytes.to_le_bytes());
        buf[96..104].copy_from_slice(&self.storage_byte_seconds.to_le_bytes());
        buf
    }

    /// Adds another resource vector with saturating arithmetic to prevent overflow.
    #[must_use]
    pub fn saturating_add(&self, other: &Self) -> Self {
        Self {
            cpu_thread_time_us: self
                .cpu_thread_time_us
                .saturating_add(other.cpu_thread_time_us),
            wasm_fuel_consumed: self
                .wasm_fuel_consumed
                .saturating_add(other.wasm_fuel_consumed),
            gpu_compute_time_us: self
                .gpu_compute_time_us
                .saturating_add(other.gpu_compute_time_us),
            npu_compute_time_us: self
                .npu_compute_time_us
                .saturating_add(other.npu_compute_time_us),
            vram_peak_byte_seconds: self
                .vram_peak_byte_seconds
                .saturating_add(other.vram_peak_byte_seconds),
            ai_prompt_tokens: self.ai_prompt_tokens.saturating_add(other.ai_prompt_tokens),
            ai_generated_tokens: self
                .ai_generated_tokens
                .saturating_add(other.ai_generated_tokens),
            ai_layer_activations_transferred: self
                .ai_layer_activations_transferred
                .saturating_add(other.ai_layer_activations_transferred),
            media_frames_encoded: self
                .media_frames_encoded
                .saturating_add(other.media_frames_encoded),
            render_pixels_completed: self
                .render_pixels_completed
                .saturating_add(other.render_pixels_completed),
            network_egress_bytes: self
                .network_egress_bytes
                .saturating_add(other.network_egress_bytes),
            network_ingress_bytes: self
                .network_ingress_bytes
                .saturating_add(other.network_ingress_bytes),
            storage_byte_seconds: self
                .storage_byte_seconds
                .saturating_add(other.storage_byte_seconds),
        }
    }
}

/// Accumulator that collects real-time resource metrics across execution engines.
#[derive(Debug, Clone, Default)]
pub struct ResourceMeteringCollector {
    current: MeteredResourceVector,
}

impl ResourceMeteringCollector {
    /// Creates a new empty collector.
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// Records CPU execution time.
    pub fn record_cpu(&mut self, thread_time_us: u64) {
        self.current.cpu_thread_time_us = self
            .current
            .cpu_thread_time_us
            .saturating_add(thread_time_us);
    }

    /// Records WASM fuel consumed.
    pub fn record_wasm_fuel(&mut self, fuel: u64) {
        self.current.wasm_fuel_consumed = self.current.wasm_fuel_consumed.saturating_add(fuel);
    }

    /// Records GPU shader compute time and VRAM allocation.
    pub fn record_gpu(&mut self, compute_time_us: u64, vram_bytes: u64, duration_sec: u64) {
        self.current.gpu_compute_time_us = self
            .current
            .gpu_compute_time_us
            .saturating_add(compute_time_us);
        let byte_sec = vram_bytes.saturating_mul(duration_sec);
        self.current.vram_peak_byte_seconds =
            self.current.vram_peak_byte_seconds.saturating_add(byte_sec);
    }

    /// Records AI token counts and layer activation transfer.
    pub fn record_ai_tokens(
        &mut self,
        prompt_tokens: u64,
        generated_tokens: u64,
        activations_transferred: u64,
    ) {
        self.current.ai_prompt_tokens = self.current.ai_prompt_tokens.saturating_add(prompt_tokens);
        self.current.ai_generated_tokens = self
            .current
            .ai_generated_tokens
            .saturating_add(generated_tokens);
        self.current.ai_layer_activations_transferred = self
            .current
            .ai_layer_activations_transferred
            .saturating_add(activations_transferred);
    }

    /// Records 3D render pixels completed.
    pub fn record_render_pixels(&mut self, pixels: u64) {
        self.current.render_pixels_completed =
            self.current.render_pixels_completed.saturating_add(pixels);
    }

    /// Records media frames encoded.
    pub fn record_media_frames(&mut self, frames: u64) {
        self.current.media_frames_encoded =
            self.current.media_frames_encoded.saturating_add(frames);
    }

    /// Records network I/O bytes.
    pub fn record_network(&mut self, ingress_bytes: u64, egress_bytes: u64) {
        self.current.network_ingress_bytes = self
            .current
            .network_ingress_bytes
            .saturating_add(ingress_bytes);
        self.current.network_egress_bytes = self
            .current
            .network_egress_bytes
            .saturating_add(egress_bytes);
    }

    /// Records storage footprint residency.
    pub fn record_storage(&mut self, byte_seconds: u64) {
        self.current.storage_byte_seconds = self
            .current
            .storage_byte_seconds
            .saturating_add(byte_seconds);
    }

    /// Snapshot the current resource vector.
    #[must_use]
    pub fn snapshot(&self) -> MeteredResourceVector {
        self.current
    }

    /// Finalizes the collection and computes the BLAKE3 digest of output payload.
    #[must_use]
    pub fn finalize(self, output_bytes: &[u8]) -> (MeteredResourceVector, [u8; 32]) {
        let output_digest = *blake3::hash(output_bytes).as_bytes();
        (self.current, output_digest)
    }
}

/// Plausibility bounds verifier rejecting physically impossible or inflated resource claims.
#[derive(Debug, Default)]
pub struct SanityBoundsChecker;

impl SanityBoundsChecker {
    /// Validates AI token generation claims against verified coordinator token stream and wall duration.
    pub fn check_ai_tokens(
        claimed_generated: u64,
        actual_verified_tokens: u64,
        wall_duration_ms: u64,
    ) -> Result<(), LedgerError> {
        // Invariant: Claimed generated tokens cannot exceed tokens verified in the coordinator stream
        if claimed_generated > actual_verified_tokens {
            return Err(LedgerError::InflatedResourceClaim {
                dimension: "ai_generated_tokens".to_string(),
                claimed: claimed_generated,
                max_plausible: actual_verified_tokens,
                reason: "Worker claimed more tokens than verified in output stream".to_string(),
            });
        }

        // Invariant: Claimed generation throughput cannot exceed physical hardware speed
        // High-end desktop GPU max ~ 500 tokens/sec. Allow 1,000 tok/sec safety ceiling.
        let duration_sec = (wall_duration_ms as f64) / 1000.0;
        let max_plausible_tokens = ((duration_sec * 1000.0).ceil() as u64).max(64);

        if claimed_generated > max_plausible_tokens {
            return Err(LedgerError::InflatedResourceClaim {
                dimension: "ai_generated_tokens_rate".to_string(),
                claimed: claimed_generated,
                max_plausible: max_plausible_tokens,
                reason: format!("Generation rate exceeds physical accelerator ceiling ({claimed_generated} tokens in {wall_duration_ms} ms)"),
            });
        }

        Ok(())
    }

    /// Validates GPU rendering claims against image resolution and sample counts.
    pub fn check_render_pixels(
        claimed_pixels: u64,
        width: u32,
        height: u32,
        samples_per_pixel: u32,
    ) -> Result<(), LedgerError> {
        let total_possible = (width as u64)
            .saturating_mul(height as u64)
            .saturating_mul(samples_per_pixel as u64);

        if claimed_pixels > total_possible {
            return Err(LedgerError::InflatedResourceClaim {
                dimension: "render_pixels_completed".to_string(),
                claimed: claimed_pixels,
                max_plausible: total_possible,
                reason: format!("Claimed pixels exceed resolution ({width}x{height}) * samples ({samples_per_pixel})"),
            });
        }
        Ok(())
    }

    /// Validates media transcode frame claims against video duration and framerate.
    pub fn check_media_frames(
        claimed_frames: u64,
        duration_sec: u64,
        fps: u32,
    ) -> Result<(), LedgerError> {
        // Multi-pass encoding may process at most 2x the total frame count
        let max_possible = duration_sec
            .saturating_mul(fps as u64)
            .saturating_mul(2)
            .max(120);

        if claimed_frames > max_possible {
            return Err(LedgerError::InflatedResourceClaim {
                dimension: "media_frames_encoded".to_string(),
                claimed: claimed_frames,
                max_plausible: max_possible,
                reason: format!("Claimed frames exceed video duration ({duration_sec}s) * fps ({fps}) * 2 passes"),
            });
        }
        Ok(())
    }

    /// Validates CPU thread execution duration against wall-clock time and logical core count.
    pub fn check_cpu_time(
        claimed_cpu_us: u64,
        wall_duration_ms: u64,
        max_threads: u32,
    ) -> Result<(), LedgerError> {
        let max_possible_us = wall_duration_ms
            .saturating_mul(1000)
            .saturating_mul(max_threads as u64);

        if claimed_cpu_us > max_possible_us {
            return Err(LedgerError::InflatedResourceClaim {
                dimension: "cpu_thread_time_us".to_string(),
                claimed: claimed_cpu_us,
                max_plausible: max_possible_us,
                reason: format!("CPU execution time ({claimed_cpu_us} us) exceeds wall time ({wall_duration_ms} ms) * {max_threads} threads"),
            });
        }
        Ok(())
    }
}
