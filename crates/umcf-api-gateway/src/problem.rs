// problem.rs
// RFC 9457 Problem Details for HTTP APIs (application/problem+json)
// Standardized machine-readable error responses across all UMCF /api/v1/* routes.

use axum::http::StatusCode;
use axum::response::{IntoResponse, Response};
use serde::{Deserialize, Serialize};

/// Detailed descriptor for a specific invalid query/body parameter.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct InvalidParam {
    /// Field or parameter name that failed validation.
    pub name: String,
    /// Human-readable explanation of why the parameter is invalid.
    pub reason: String,
}

/// Standardized RFC 9457 Problem Details object.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Rfc9457ProblemDetails {
    /// A URI reference that identifies the problem type.
    #[serde(rename = "type")]
    pub error_type: String,
    /// A short, human-readable summary of the problem type.
    pub title: String,
    /// The HTTP status code generated by the origin server.
    pub status: u16,
    /// A human-readable explanation specific to this occurrence of the problem.
    pub detail: String,
    /// A URI reference that identifies the specific occurrence of the problem.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub instance: Option<String>,
    /// Machine-readable UMCF error code (e.g. `UMCF_AUTH_INSUFFICIENT_SCOPE`).
    pub error_code: String,
    /// Optional parameter validation errors.
    #[serde(skip_serializing_if = "Vec::is_empty", default)]
    pub invalid_params: Vec<InvalidParam>,
}

impl Rfc9457ProblemDetails {
    /// Constructs an Unauthorized (401) problem details response.
    #[must_use]
    pub fn unauthorized(detail: impl Into<String>) -> Self {
        Self {
            error_type: "https://umcf.dev/errors/unauthorized".to_string(),
            title: "Authentication Required".to_string(),
            status: 401,
            detail: detail.into(),
            instance: None,
            error_code: "UMCF_AUTH_MISSING_TOKEN".to_string(),
            invalid_params: Vec::new(),
        }
    }

    /// Constructs a Forbidden (403) problem details response for insufficient capability scopes.
    #[must_use]
    pub fn forbidden(required_scope: &str, provided_scopes: &[String]) -> Self {
        Self {
            error_type: "https://umcf.dev/errors/forbidden".to_string(),
            title: "Insufficient Capability Scope".to_string(),
            status: 403,
            detail: format!(
                "Required scope '{required_scope}' is not granted to this token. Granted scopes: [{}]",
                provided_scopes.join(", ")
            ),
            instance: None,
            error_code: "UMCF_AUTH_INSUFFICIENT_SCOPE".to_string(),
            invalid_params: Vec::new(),
        }
    }

    /// Constructs a Rate Limited (429) problem details response.
    #[must_use]
    pub fn rate_limited(retry_after_ms: u64) -> Self {
        Self {
            error_type: "https://umcf.dev/errors/rate-limited".to_string(),
            title: "Too Many Requests".to_string(),
            status: 429,
            detail: format!("Rate limit bucket exhausted. Please retry after {retry_after_ms} ms."),
            instance: None,
            error_code: "UMCF_RATE_LIMIT_EXCEEDED".to_string(),
            invalid_params: Vec::new(),
        }
    }

    /// Constructs a Not Found (404) problem details response.
    #[must_use]
    pub fn not_found(resource: &str, identifier: &str) -> Self {
        Self {
            error_type: "https://umcf.dev/errors/not-found".to_string(),
            title: format!("{resource} Not Found"),
            status: 404,
            detail: format!(
                "{resource} with identifier '{identifier}' was not found in mesh registry."
            ),
            instance: None,
            error_code: "UMCF_RESOURCE_NOT_FOUND".to_string(),
            invalid_params: Vec::new(),
        }
    }

    /// Constructs a Bad Request (400) validation problem details response.
    #[must_use]
    pub fn validation_error(detail: impl Into<String>, invalid_params: Vec<InvalidParam>) -> Self {
        Self {
            error_type: "https://umcf.dev/errors/validation-error".to_string(),
            title: "Validation Error".to_string(),
            status: 400,
            detail: detail.into(),
            instance: None,
            error_code: "UMCF_VALIDATION_ERROR".to_string(),
            invalid_params,
        }
    }
}

impl IntoResponse for Rfc9457ProblemDetails {
    fn into_response(self) -> Response {
        let status = StatusCode::from_u16(self.status).unwrap_or(StatusCode::INTERNAL_SERVER_ERROR);
        let body = serde_json::to_string_pretty(&self).unwrap_or_else(|_| "{}".to_string());
        (
            status,
            [
                (axum::http::header::CONTENT_TYPE, "application/problem+json"),
                (axum::http::header::ACCESS_CONTROL_ALLOW_ORIGIN, "*"),
            ],
            body,
        )
            .into_response()
    }
}
